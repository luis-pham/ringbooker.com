function normalizeCity(city: string): string {
  return city.trim().toLowerCase().replace(/\s+/g, ' ');
}

function normalizeState(state: string): string {
  return state.trim().toUpperCase();
}

/**
 * Returns the US area code (NPA) for a given city, state abbreviation, and ZIP.
 * Returns null when the state is not a recognised US state abbreviation.
 */
export function getAreaCode(city: string, state: string, zip: string): string | null {
  const st = normalizeState(state);

  // 1. City + state exact match
  const cityNorm = normalizeCity(city);
  const cityMap = CITY_AREA_CODES[st];
  if (cityMap) {
    const fromCity = cityMap[cityNorm];
    if (fromCity) return fromCity;
  }

  // 2. ZIP prefix (first 3 digits)
  const zip3 = zip.replace(/\D/g, '').slice(0, 3);
  if (zip3.length === 3) {
    const fromZip = ZIP3_AREA_CODE[zip3];
    if (fromZip) return fromZip;
  }

  // 3. State primary area code
  const stateCodes = STATE_AREA_CODES[st];
  return stateCodes?.[0] ?? null;
}
